#!/usr/bin/env bash
# Stands up NetBox with fresh secrets and gets it ready for the dashboard. Safe to re-run.
#
#   ./setup.sh                      first install, or re-apply after an upgrade
#   ./setup.sh --new-dashboard-token  replace the dashboard's API token
#   ./setup.sh --no-pull            use the images already on this machine
#
# Settings (optional) go in deploy/netbox/.env: NETBOX_PORT (8000), NETBOX_BIND (0.0.0.0),
# NETBOX_VERSION, ADMIN_EMAIL, NETBOX_URL (how other machines reach this one).
set -euo pipefail
cd "$(dirname "$0")"

die() { echo "error: $*" >&2; exit 1; }
say() { printf '\033[1m%s\033[0m\n' "$*"; }

PULL=1
NEW_TOKEN=0
for arg in "$@"; do
  case "$arg" in
    --no-pull) PULL=0 ;;
    --new-dashboard-token) NEW_TOKEN=1 ;;
    -h | --help) sed -n '2,10p' "$0"; exit 0 ;;
    *) die "unknown option $arg (see --help)" ;;
  esac
done

command -v docker >/dev/null || die "Docker isn't installed: https://docs.docker.com/engine/install/"
docker compose version >/dev/null 2>&1 || die "Docker Compose v2 is needed (the 'docker compose' plugin)"
docker info >/dev/null 2>&1 || die "can't talk to the Docker daemon — is it running, and is this user allowed to use it?"
[ -f ../../server/netbox/schema.json ] || die "run this from a full checkout of the repository"

if [ -f .env ]; then
  set -a
  # shellcheck disable=SC1091
  . ./.env
  set +a
fi
PORT="${NETBOX_PORT:-8000}"

# Random strings from the kernel's CSPRNG; letters and digits only, so they're safe in env files.
# `tr` dies of SIGPIPE when `head` has enough, so pipefail is off inside this one subshell.
rand() { (set +o pipefail; LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom 2>/dev/null | head -c "$1"); }

umask 077
mkdir -p env secrets

if [ ! -f env/netbox.env ]; then
  DB_PASSWORD=$(rand 32)
  REDIS_PASSWORD=$(rand 32)
  REDIS_CACHE_PASSWORD=$(rand 32)
  cat >env/netbox.env <<EOF
# Generated by setup.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Keep private; back it up with the database.
DB_HOST=postgres
DB_NAME=netbox
DB_USER=netbox
DB_PASSWORD=$DB_PASSWORD
REDIS_HOST=redis
REDIS_PASSWORD=$REDIS_PASSWORD
REDIS_DATABASE=0
REDIS_SSL=false
REDIS_CACHE_HOST=redis-cache
REDIS_CACHE_PASSWORD=$REDIS_CACHE_PASSWORD
REDIS_CACHE_DATABASE=1
REDIS_CACHE_SSL=false
SECRET_KEY=$(rand 64)
# Hashes v2 API tokens. Losing it invalidates every v2 token.
API_TOKEN_PEPPER_1=$(rand 64)
SKIP_SUPERUSER=true
MEDIA_ROOT=/opt/netbox/netbox/media
GRAPHQL_ENABLED=true
WEBHOOKS_ENABLED=true
METRICS_ENABLED=false
RELEASE_CHECK_URL=https://api.github.com/repos/netbox-community/netbox/releases
EOF
  printf 'POSTGRES_DB=netbox\nPOSTGRES_USER=netbox\nPOSTGRES_PASSWORD=%s\n' "$DB_PASSWORD" >env/postgres.env
  printf 'REDIS_PASSWORD=%s\n' "$REDIS_PASSWORD" >env/redis.env
  printf 'REDIS_PASSWORD=%s\n' "$REDIS_CACHE_PASSWORD" >env/redis-cache.env
  say "Generated new secrets in deploy/netbox/env/"
fi

if [ ! -f secrets/admin.env ]; then
  printf 'ADMIN_USER=admin\nADMIN_PASSWORD=%s\n' "$(rand 24)" >secrets/admin.env
fi
set -a
# shellcheck disable=SC1091
. ./secrets/admin.env
set +a
export ADMIN_EMAIL="${ADMIN_EMAIL:-}"

if [ "$PULL" = 1 ]; then
  say "Pulling images…"
  docker compose pull --quiet
fi
say "Starting NetBox…"
# The worker waits for NetBox to be healthy, which on a first start (or an upgrade) means waiting
# for database migrations. Start everything else first and wait here, where we can be patient.
docker compose up -d postgres redis redis-cache netbox

say "Waiting for NetBox (the first start runs database migrations; that can take several minutes)…"
cid=$(docker compose ps -q netbox)
status=starting
for _ in $(seq 1 180); do
  status=$(docker inspect -f '{{.State.Health.Status}}' "$cid" 2>/dev/null || echo starting)
  [ "$status" = healthy ] && break
  # "unhealthy" is normal while migrations run; only a stopped container is a real failure.
  if [ "$(docker inspect -f '{{.State.Running}}' "$cid")" != true ]; then
    docker compose logs --tail 40 netbox >&2
    die "NetBox stopped; the log above says why"
  fi
  printf '.'
  sleep 5
done
echo
[ "$status" = healthy ] || { docker compose logs --tail 40 netbox >&2; die "NetBox still isn't healthy after 15 minutes"; }
docker compose up -d

MAKE_TOKEN=0
if [ ! -f secrets/dashboard.env ] || [ "$NEW_TOKEN" = 1 ]; then MAKE_TOKEN=1; fi
say "Configuring NetBox for the dashboard…"
if ! out=$(docker compose exec -T \
  -e DASHBOARD_SCHEMA="$(cat ../../server/netbox/schema.json)" \
  -e ADMIN_USER -e ADMIN_PASSWORD -e ADMIN_EMAIL \
  -e MAKE_DASHBOARD_TOKEN="$MAKE_TOKEN" \
  netbox /opt/netbox/venv/bin/python /opt/netbox/netbox/manage.py shell --no-startup --no-imports --interface python \
  <setup.py 2>&1); then
  printf '%s\n' "$out" >&2
  die "configuring NetBox failed; the output above says why"
fi
# Show what changed, without the config-loading chatter or the image's own deprecation notice.
printf '%s\n' "$out" | grep -vE '^DASHBOARD_TOKEN=|loaded config|FutureWarning|warnings\.warn' | sed 's/^/  /' || true

host_ip=$( (hostname -I 2>/dev/null || true) | awk '{print $1}')
url="${NETBOX_URL:-http://${host_ip:-localhost}:$PORT}"
token=$(printf '%s\n' "$out" | sed -n 's/^DASHBOARD_TOKEN=//p')
if [ -n "$token" ]; then
  printf '# For the dashboard'"'"'s .env — a read-only token for the "dashboard" user.\nNETBOX_URL=%s\nNETBOX_TOKEN=%s\n' "$url" "$token" >secrets/dashboard.env
fi

echo
say "NetBox is up: $url"
echo "  Log in as ${ADMIN_USER}; the password is in deploy/netbox/secrets/admin.env"
echo "  Dashboard settings (URL + read-only token) are in deploy/netbox/secrets/dashboard.env"
echo "  Back up regularly with ./backup.sh — everything in env/ and secrets/ is needed to restore."
